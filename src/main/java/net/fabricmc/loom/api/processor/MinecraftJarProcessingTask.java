package net.fabricmc.loom.api.processor;

import org.gradle.api.DefaultTask;
import org.gradle.api.file.RegularFileProperty;
import org.gradle.api.tasks.InputFile;
import org.gradle.api.tasks.OutputFile;
import org.gradle.api.tasks.PathSensitive;
import org.gradle.api.tasks.PathSensitivity;
import org.gradle.work.DisableCachingByDefault;
import org.jetbrains.annotations.ApiStatus;

/**
 * A task that transforms one named Minecraft jar into another.
 * Loom sets the input jar when the task is registered as a processing step.
 * The task owner must set its output jar and declare any additional inputs.
 */
@ApiStatus.Experimental
@DisableCachingByDefault(because = "Subclasses decide whether their processing is safe to cache")
public abstract class MinecraftJarProcessingTask extends DefaultTask {
	@InputFile
	@PathSensitive(PathSensitivity.NONE)
	public abstract RegularFileProperty getInputJar();

	@OutputFile
	public abstract RegularFileProperty getOutputJar();
}
